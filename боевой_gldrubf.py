def calculate_sar(
    df,
    start,
    inc,
    maximum
):

    high = df["high"].to_numpy()
    low = df["low"].to_numpy()
    close = df["close"].to_numpy()

    n = len(df)


    sar = np.full(
        n,
        np.nan
    )

    ep = np.full(
        n,
        np.nan
    )

    af = np.full(
        n,
        np.nan
    )

    trend = np.ones(
        n,
        dtype=int
    )


    if n == 0:

        return sar, trend


    sar[0] = close[0]
    ep[0] = close[0]
    af[0] = start
    trend[0] = 1


    for i in range(
        1,
        n
    ):

        prev_sar = sar[i - 1]
        prev_ep = ep[i - 1]
        prev_af = af[i - 1]
        prev_trend = trend[i - 1]


        # ====================================================
        # UP TREND
        # ====================================================

        if prev_trend == 1:

            current_sar = (

                prev_sar

                + prev_af
                * (
                    prev_ep
                    - prev_sar
                )
            )


            if i >= 2:

                current_sar = min(

                    current_sar,

                    low[i - 1],

                    low[i - 2]
                )

            else:

                current_sar = min(

                    current_sar,

                    low[i - 1]
                )


            # ------------------------------------------------
            # REVERSAL
            # ------------------------------------------------

            if low[i] < current_sar:

                trend[i] = -1

                sar[i] = prev_ep

                ep[i] = low[i]

                af[i] = start


            # ------------------------------------------------
            # CONTINUE UP
            # ------------------------------------------------

            else:

                trend[i] = 1

                sar[i] = current_sar


                if high[i] > prev_ep:

                    ep[i] = high[i]

                    af[i] = min(

                        prev_af + inc,

                        maximum
                    )

                else:

                    ep[i] = prev_ep

                    af[i] = prev_af


        # ====================================================
        # DOWN TREND
        # ====================================================

        else:

            current_sar = (

                prev_sar

                + prev_af
                * (
                    prev_ep
                    - prev_sar
                )
            )


            if i >= 2:

                current_sar = max(

                    current_sar,

                    high[i - 1],

                    high[i - 2]
                )

            else:

                current_sar = max(

                    current_sar,

                    high[i - 1]
                )


            # ------------------------------------------------
            # REVERSAL
            # ------------------------------------------------

            if high[i] > current_sar:

                trend[i] = 1

                sar[i] = prev_ep

                ep[i] = high[i]

                af[i] = start


            # ------------------------------------------------
            # CONTINUE DOWN
            # ------------------------------------------------

            else:

                trend[i] = -1

                sar[i] = current_sar


                if low[i] < prev_ep:

                    ep[i] = low[i]

                    af[i] = min(

                        prev_af + inc,

                        maximum
                    )

                else:

                    ep[i] = prev_ep

                    af[i] = prev_af


    return sar, trend

