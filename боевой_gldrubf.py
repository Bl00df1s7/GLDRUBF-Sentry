def quotation_to_float(value):
    """
    Безопасное преобразование Quotation в float.
    """

    if value is None:
        return np.nan


    if isinstance(
        value,
        (int, float, np.number)
    ):

        return float(value)


    if (
        hasattr(value, "units")
        and hasattr(value, "nano")
    ):

        return (
            float(value.units)
            + float(value.nano)
            / 1_000_000_000
        )


    if hasattr(value, "value"):

        return float(value.value)


    return float(value)


def candle_to_row(candle):

    return {

        "time": candle.time,

        "open": quotation_to_float(
            candle.open
        ),

        "high": quotation_to_float(
            candle.high
        ),

        "low": quotation_to_float(
            candle.low
        ),

        "close": quotation_to_float(
            candle.close
        ),

        "volume": candle.volume,
    }


def load_recent_candles(
    uid,
    candles_count=200
):

    now_utc = datetime.now(
        timezone.utc
    )


    # 4H = 6 свечей в сутки.
    # Добавляем запас истории.

    days = int(
        candles_count / 6
    ) + 10


    start_date = (
        now_utc
        - timedelta(days=days)
    )


    rows = []

    current = start_date

    chunk = timedelta(days=90)


    while current < now_utc:

        chunk_end = min(
            current + chunk,
            now_utc
        )


        with Client(TOKEN) as services:

            response = (
                services.market_data.get_candles(

                    instrument_id=uid,

                    from_=current,

                    to=chunk_end,

                    interval=(
                        CandleInterval
                        .CANDLE_INTERVAL_4_HOUR
                    ),
                )
            )


        rows.extend(

            candle_to_row(candle)

            for candle
            in response.candles
        )


        current = chunk_end


    df = pd.DataFrame(rows)


    if df.empty:

        return df


    df["time"] = pd.to_datetime(
        df["time"],
        utc=True
    )


    df = (

        df

        .drop_duplicates("time")

        .sort_values("time")

        .reset_index(drop=True)
    )


    return (
        df
        .tail(candles_count)
        .reset_index(drop=True)
    )

