def calculate_atr(
    df,
    length
):

    high = df["high"]
    low = df["low"]
    close = df["close"]

    prev_close = close.shift(1)


    tr = pd.concat(

        [

            high - low,

            (
                high - prev_close
            ).abs(),

            (
                low - prev_close
            ).abs(),

        ],

        axis=1

    ).max(axis=1)


    return (
        tr
        .rolling(length)
        .mean()
    )


def prepare_indicators(df):

    data = (
        df
        .copy()
        .reset_index(drop=True)
    )


    # ========================================================
    # ATR
    # ========================================================

    data["atr"] = calculate_atr(
        data,
        ATR_LEN
    )


    # ========================================================
    # DONCHIAN
    #
    # Только предыдущие свечи.
    # ========================================================

    data["donchian_upper"] = (

        data["high"]

        .rolling(DONCHIAN_LEN)

        .max()

        .shift(1)
    )


    data["donchian_lower"] = (

        data["low"]

        .rolling(DONCHIAN_LEN)

        .min()

        .shift(1)
    )


    # ========================================================
    # ENTRY SIGNALS
    # ========================================================

    data["long_signal"] = (

        data["close"]
        > data["donchian_upper"]
    )


    data["short_signal"] = (

        data["close"]
        < data["donchian_lower"]
    )


    return data

